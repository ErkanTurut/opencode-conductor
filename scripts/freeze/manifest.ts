#!/usr/bin/env bun
/**
 * Freeze manifest for the legacy supervisor tree.
 *
 * `tools/opencode-supervisor` is the pre-port implementation. It must stay
 * byte-identical until `p4-saul-switch` flips the plugin over to this package,
 * so the port can be compared against a known-good reference and rolled back by
 * re-pointing a single import.
 *
 * The manifest records a sha256 per file, sorted by repo-relative posix path,
 * plus a `treeHash`: sha256 over the sorted `<path>:<hash>` lines joined with
 * `\n` (no trailing newline). Nothing location-dependent is hashed, so the tree
 * hashes the same in a checkout, a worktree, or a copy at an alternate root.
 *
 * Excluded on purpose — generated or ignored artifacts, not reviewable source:
 *   - `node_modules/` (any depth)
 *   - `dist/` (any depth)
 *   - `bun.lock` (regenerated by `bun install`)
 * Non-regular entries (symlinks, sockets, …) are skipped. Replacing a tracked
 * file with one therefore shows up as a removal, not a silent pass.
 *
 * Usage (from the repo root):
 *   bun tools/opencode-conductor/scripts/freeze/manifest.ts
 *   bun tools/opencode-conductor/scripts/freeze/manifest.ts --update
 *   bun tools/opencode-conductor/scripts/freeze/manifest.ts --root <dir>
 *   bun tools/opencode-conductor/scripts/freeze/manifest.ts --manifest <file>
 *
 * Exit codes: 0 tree matches, 1 drift, 2 usage/configuration error.
 * `--root` / `--manifest` (and the matching `SUPERVISOR_FREEZE_ROOT` /
 * `SUPERVISOR_FREEZE_MANIFEST` env vars) exist so the gate can be exercised
 * against a scratch copy; they never change what the committed manifest claims.
 */
import { createHash } from 'node:crypto'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Repo-relative location of the frozen subtree written into the manifest. */
export const FROZEN_ROOT_REL = 'tools/opencode-supervisor'
/** Package-relative location of the committed manifest. */
export const MANIFEST_REL = 'docs/freeze/supervisor-freeze.json'
/** Directories skipped at any depth (generated / ignored). */
export const SKIP_DIR_NAMES = new Set(['node_modules', 'dist'])
/** Files skipped at any depth (generated / ignored). */
export const SKIP_FILE_NAMES = new Set(['bun.lock'])

/** `tools/opencode-conductor` — two levels up from `scripts/freeze`. */
export const PACKAGE_ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)))

export const ROOT_ENV_VAR = 'SUPERVISOR_FREEZE_ROOT'
export const MANIFEST_ENV_VAR = 'SUPERVISOR_FREEZE_MANIFEST'

export interface FreezeManifest {
  generatedAt: string
  root: string
  files: Record<string, string>
  treeHash: string
}

export interface FreezeDiff {
  added: string[]
  removed: string[]
  changed: string[]
}

export interface CheckResult {
  ok: boolean
  /** Hash of the tree as it exists on disk right now. */
  actualTreeHash: string
  diff: FreezeDiff
}

export interface CliIo {
  out: (line: string) => void
  err: (line: string) => void
}

const DEFAULT_IO: CliIo = {
  out: (line) => console.log(line),
  err: (line) => console.error(line),
}

/**
 * Repo root for this checkout. Path math on purpose: the package always sits at
 * `<repo>/tools/opencode-conductor`, and a purely relative answer keeps the
 * manifest free of absolute paths. A standalone copy never reaches the scan
 * because callers check the subtree first.
 */
export function inferRepoRoot(packageRoot: string = PACKAGE_ROOT): string {
  return resolve(packageRoot, '..', '..')
}

export function defaultFrozenRoot(packageRoot: string = PACKAGE_ROOT): string {
  return join(inferRepoRoot(packageRoot), FROZEN_ROOT_REL)
}

export function defaultManifestPath(packageRoot: string = PACKAGE_ROOT): string {
  return join(packageRoot, MANIFEST_REL)
}

function sha256(data: Buffer | string): string {
  return createHash('sha256').update(data).digest('hex')
}

function comparePaths(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}

function toPosix(path: string): string {
  return sep === '/' ? path : path.split(sep).join('/')
}

/** Relative posix paths of every tracked file, sorted. */
export function walkTree(rootDir: string): string[] {
  const found: string[] = []
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const absolute = join(dir, entry.name)
      if (entry.isDirectory()) {
        if (SKIP_DIR_NAMES.has(entry.name)) continue
        walk(absolute)
        continue
      }
      if (!entry.isFile()) continue
      if (SKIP_FILE_NAMES.has(entry.name)) continue
      found.push(toPosix(relative(rootDir, absolute)))
    }
  }
  walk(rootDir)
  return found.sort(comparePaths)
}

/** sha256 per relative path, in sorted-path order. */
export function hashTree(rootDir: string): Record<string, string> {
  const files: Record<string, string> = Object.create(null)
  for (const relPath of walkTree(rootDir)) {
    files[relPath] = sha256(readFileSync(join(rootDir, relPath)))
  }
  return files
}

/** sha256 over the sorted `<path>:<hash>` lines, joined with `\n`. */
export function computeTreeHash(files: Record<string, string>): string {
  const lines = Object.keys(files)
    .sort(comparePaths)
    .map((path) => `${path}:${files[path]}`)
  return sha256(lines.join('\n'))
}

export function buildManifest(
  rootDir: string,
  generatedAt: string = new Date().toISOString(),
): FreezeManifest {
  const files = hashTree(rootDir)
  return {
    generatedAt,
    root: FROZEN_ROOT_REL,
    files,
    treeHash: computeTreeHash(files),
  }
}

export function diffManifests(
  expected: Record<string, string>,
  actual: Record<string, string>,
): FreezeDiff {
  const added = Object.keys(actual)
    .filter((path) => !(path in expected))
    .sort(comparePaths)
  const removed = Object.keys(expected)
    .filter((path) => !(path in actual))
    .sort(comparePaths)
  const changed = Object.keys(expected)
    .filter((path) => path in actual && expected[path] !== actual[path])
    .sort(comparePaths)
  return { added, removed, changed }
}

export function diffIsEmpty(diff: FreezeDiff): boolean {
  return diff.added.length === 0 && diff.removed.length === 0 && diff.changed.length === 0
}

/** One line per drift, `+` added / `-` removed / `~` changed. */
export function formatDiff(diff: FreezeDiff): string[] {
  return [
    ...diff.added.map((path) => `  + ${path}`),
    ...diff.removed.map((path) => `  - ${path}`),
    ...diff.changed.map((path) => `  ~ ${path}`),
  ]
}

function isHex64(value: unknown): value is string {
  return typeof value === 'string' && /^[0-9a-f]{64}$/.test(value)
}

function assertManifestPath(path: string): void {
  const segments = path.split('/')
  if (
    path.length === 0 ||
    isAbsolute(path) ||
    path.includes('\\') ||
    segments.some((segment) => segment === '' || segment === '.' || segment === '..')
  ) {
    throw new Error(`manifest path is not a plain relative path: ${JSON.stringify(path)}`)
  }
}

/** Parse and integrity-check a manifest document. Throws on any inconsistency. */
export function parseManifest(raw: unknown): FreezeManifest {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    throw new Error('manifest must be a JSON object')
  }
  const candidate = raw as Partial<FreezeManifest>
  if (typeof candidate.generatedAt !== 'string' || candidate.generatedAt.length === 0) {
    throw new Error('manifest.generatedAt must be a non-empty string')
  }
  if (typeof candidate.root !== 'string' || isAbsolute(candidate.root)) {
    throw new Error('manifest.root must be a relative path')
  }
  if (typeof candidate.files !== 'object' || candidate.files === null) {
    throw new Error('manifest.files must be an object of path -> sha256')
  }
  const files: Record<string, string> = Object.create(null)
  for (const [path, hash] of Object.entries(candidate.files)) {
    assertManifestPath(path)
    if (!isHex64(hash)) throw new Error(`manifest.files[${JSON.stringify(path)}] is not a sha256`)
    files[path] = hash
  }
  if (!isHex64(candidate.treeHash)) {
    throw new Error('manifest.treeHash must be a sha256')
  }
  const expected = computeTreeHash(files)
  if (candidate.treeHash !== expected) {
    throw new Error(
      `manifest.treeHash does not match its file map (recorded ${candidate.treeHash}, computed ${expected})`,
    )
  }
  return {
    generatedAt: candidate.generatedAt,
    root: candidate.root,
    files,
    treeHash: candidate.treeHash,
  }
}

export function readManifest(path: string): FreezeManifest {
  return parseManifest(JSON.parse(readFileSync(path, 'utf8')))
}

export function writeManifest(path: string, manifest: FreezeManifest): void {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, `${JSON.stringify(manifest, null, 2)}\n`)
}

/** Hash the tree on disk and compare it with a manifest. */
export function checkTree(manifest: FreezeManifest, rootDir: string): CheckResult {
  const actual = hashTree(rootDir)
  const actualTreeHash = computeTreeHash(actual)
  const diff = diffManifests(manifest.files, actual)
  return {
    ok: diffIsEmpty(diff) && actualTreeHash === manifest.treeHash,
    actualTreeHash,
    diff,
  }
}

export interface CliOptions {
  update: boolean
  help: boolean
  rootDir: string
  manifestPath: string
}

export class UsageError extends Error {}

function takeValue(argv: string[], index: number, flag: string): string {
  const value = argv[index + 1]
  if (value === undefined || value.startsWith('--')) {
    throw new UsageError(`${flag} requires a value`)
  }
  return value
}

export function parseArgs(argv: string[]): CliOptions {
  const envRoot = process.env[ROOT_ENV_VAR]
  const envManifest = process.env[MANIFEST_ENV_VAR]
  const options: CliOptions = {
    update: false,
    help: false,
    rootDir: envRoot ? resolve(process.cwd(), envRoot) : defaultFrozenRoot(),
    manifestPath: envManifest ? resolve(process.cwd(), envManifest) : defaultManifestPath(),
  }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--update') {
      options.update = true
      continue
    }
    if (arg === '--help' || arg === '-h') {
      options.help = true
      continue
    }
    if (arg === '--root') {
      options.rootDir = resolve(process.cwd(), takeValue(argv, index, '--root'))
      index += 1
      continue
    }
    if (arg.startsWith('--root=')) {
      options.rootDir = resolve(process.cwd(), arg.slice('--root='.length))
      continue
    }
    if (arg === '--manifest') {
      options.manifestPath = resolve(process.cwd(), takeValue(argv, index, '--manifest'))
      index += 1
      continue
    }
    if (arg.startsWith('--manifest=')) {
      options.manifestPath = resolve(process.cwd(), arg.slice('--manifest='.length))
      continue
    }
    throw new UsageError(`unknown argument: ${arg}`)
  }
  return options
}

const USAGE = [
  'usage: bun tools/opencode-conductor/scripts/freeze/manifest.ts [--update]',
  '           [--root <dir>] [--manifest <file>]',
].join('\n')

function displayPath(path: string): string {
  const prefix = `${PACKAGE_ROOT}${sep}`
  return path.startsWith(prefix) ? toPosix(path.slice(prefix.length)) : path
}

/**
 * Entry point shared by `manifest.ts` and `assert-supervisor-frozen.ts`.
 * `assert-supervisor-frozen.ts` is deliberately a two-line wrapper so both
 * commands can never disagree about what "frozen" means.
 */
export function runCli(argv: string[], io: CliIo = DEFAULT_IO): number {
  let options: CliOptions
  try {
    options = parseArgs(argv)
  } catch (error) {
    io.err(`freeze: ${error instanceof Error ? error.message : String(error)}`)
    io.err(USAGE)
    return 2
  }

  if (options.help) {
    io.out(USAGE)
    return 0
  }

  if (!existsSync(options.rootDir) || !statSync(options.rootDir).isDirectory()) {
    io.err(`freeze: frozen tree not found at ${options.rootDir}`)
    return 2
  }

  if (options.update) {
    const next = buildManifest(options.rootDir)
    const previous = safeReadManifest(options.manifestPath)
    // Keep the original timestamp when the content has not moved, so a
    // deliberate re-freeze with no changes is a true no-op in git.
    if (previous !== null && previous.treeHash === next.treeHash) {
      next.generatedAt = previous.generatedAt
    }
    writeManifest(options.manifestPath, next)
    io.out(
      `freeze: wrote ${displayPath(options.manifestPath)} (${Object.keys(next.files).length} files, treeHash ${next.treeHash})`,
    )
    return 0
  }

  let manifest: FreezeManifest
  try {
    manifest = readManifest(options.manifestPath)
  } catch (error) {
    if (
      typeof error === 'object' &&
      error !== null &&
      (error as { code?: unknown }).code === 'ENOENT'
    ) {
      io.err(
        `freeze: manifest missing at ${displayPath(options.manifestPath)} — run "bun tools/opencode-conductor/scripts/freeze/manifest.ts --update"`,
      )
      return 2
    }
    io.err(`freeze: ${error instanceof Error ? error.message : String(error)}`)
    return 2
  }

  const result = checkTree(manifest, options.rootDir)
  if (result.ok) {
    io.out(`FREEZE_OK ${manifest.treeHash}`)
    return 0
  }

  io.out('FREEZE_DRIFT')
  for (const line of formatDiff(result.diff)) io.out(line)
  io.out(
    `freeze: ${result.diff.added.length} added, ${result.diff.removed.length} removed, ${result.diff.changed.length} changed; expected ${manifest.treeHash}, on-disk ${result.actualTreeHash}`,
  )
  return 1
}

function safeReadManifest(path: string): FreezeManifest | null {
  if (!existsSync(path)) return null
  try {
    return readManifest(path)
  } catch {
    return null
  }
}

if (import.meta.main) {
  process.exit(runCli(process.argv.slice(2)))
}
