import { afterEach, describe, expect, test } from 'bun:test'
import { mkdtempSync, mkdirSync, readFileSync, symlinkSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { readAgentDocument, saveAgentDocument, readProjectSettings, loadProjectSettings, saveProjectSettings, __setConfigurationStoreBeforeCommitForTests } from '../../src/runtime/configuration-store'

const fixtures: string[] = []
afterEach(() => { __setConfigurationStoreBeforeCommitForTests(); for (const path of fixtures.splice(0)) rmSync(path, { recursive: true, force: true }) })
function fixture() {
  const base = mkdtempSync(join(tmpdir(), 'conductor-config-'))
  fixtures.push(base)
  const authority = { projectRoot: join(base, 'project'), configDir: join(base, 'global') }
  mkdirSync(authority.projectRoot); mkdirSync(authority.configDir)
  return { base, authority }
}
const markdown = `---\n# description comment\ndescription: Original\nmodel: old/model\n# keep this comment\npermission:\n  bash: deny\n  skill:\n    "*": ask\n    deploy: deny\ncustom: untouched\n---\nImportant prompt\n`

describe('configuration store', () => {
  test('updates model without changing body, comments, unsupported fields or permissions', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.projectRoot, '.opencode', 'agents'), { recursive: true })
    const path = join(authority.projectRoot, '.opencode', 'agents', 'coder.md')
    writeFileSync(path, markdown)
    const before = readAgentDocument(authority, { agentId: 'coder', scope: 'project' })
    const after = saveAgentDocument(authority, { agentId: 'coder', scope: 'project', expectedRevision: before.revision, fields: { model: 'openai/model#fast' } })
    expect(after.fields.model).toBe('openai/model#fast')
    expect(after.fields.permissions).toEqual([{ action: 'shell', resource: '*', effect: 'deny' }, { action: 'skill', resource: '*', effect: 'ask' }, { action: 'skill', resource: 'deploy', effect: 'deny' }])
    expect(readFileSync(path, 'utf8')).toBe(markdown.replace('model: old/model', 'model: "openai/model#fast"'))
    expect(() => saveAgentDocument(authority, { agentId: 'coder', scope: 'project', expectedRevision: before.revision, fields: { steps: 2 } })).toThrow('revision conflict')
  })
  test('uses supplied defaults for new files and edits skill without changing other permissions', () => {
    const { authority } = fixture()
    writeFileSync(join(authority.configDir, 'opencode.jsonc'), '{}')
    mkdirSync(join(authority.projectRoot, 'assets', 'agents'), { recursive: true })
    writeFileSync(join(authority.projectRoot, 'assets', 'agents', 'coder.md'), markdown)
    const withAssets = { ...authority, assetsDir: join(authority.projectRoot, 'assets') }
    const before = readAgentDocument(withAssets, { agentId: 'coder', scope: 'global' })
    expect(before.warnings.join()).toContain('precedence')
    const saved = saveAgentDocument(withAssets, { agentId: 'coder', scope: 'global', expectedRevision: before.revision, fields: { permissions: [{ action: 'shell', resource: '*', effect: 'deny' }, { action: 'skill', resource: '*', effect: 'allow' }] } })
    expect(saved.fields.system).toBe('Important prompt\n')
    expect(saved.fields.permissions).toEqual([{ action: 'shell', resource: '*', effect: 'deny' }, { action: 'skill', resource: '*', effect: 'allow' }])
    expect(readFileSync(saved.target, 'utf8')).toContain('permissions:')
  })
  test('rejects invalid IDs, models and symlinks', () => {
    const { authority, base } = fixture()
    expect(() => readAgentDocument(authority, { agentId: '../escape', scope: 'project' })).toThrow()
    const before = readAgentDocument(authority, { agentId: 'coder', scope: 'project' })
    expect(() => saveAgentDocument(authority, { agentId: 'coder', scope: 'project', expectedRevision: before.revision, fields: { model: '../bad' } })).toThrow('Invalid model')
    symlinkSync(base, join(authority.projectRoot, '.opencode'))
    expect(() => readAgentDocument(authority, { agentId: 'coder', scope: 'project' })).toThrow('Symlinks')
  })
  test('rejects absent prompts and malformed existing files', () => {
    const { authority } = fixture()
    const before = readAgentDocument(authority, { agentId: 'coder', scope: 'project' })
    expect(() => saveAgentDocument(authority, { agentId: 'coder', scope: 'project', expectedRevision: before.revision, fields: { model: 'provider/model' } })).toThrow('source prompt')
    expect(loadProjectSettings(authority.projectRoot)).toBeNull()
    writeFileSync(join(authority.projectRoot, '.opencode', 'conductor.json'), '{ broken')
    expect(() => loadProjectSettings(authority.projectRoot)).toThrow()
  })
  test('project settings roundtrip preserves unrelated fields and rejects stale or invalid input', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.projectRoot, '.opencode'))
    const path = join(authority.projectRoot, '.opencode', 'conductor.json')
    writeFileSync(path, JSON.stringify({ custom: 42, preview: { extra: true }, memory: { other: 1 } }))
    const before = readProjectSettings(authority)
    const settings = { branches: { main: 'main', dev: 'feature/dev' }, verificationCommands: ['bun test'], preview: { provider: 'vercel' as const, url: 'https://example.com', branch: 'feature/dev' }, memory: { enabled: true } }
    const after = saveProjectSettings(authority, { expectedRevision: before.revision, settings })
    expect(after.settings!.branches).toEqual(settings.branches)
    expect(JSON.parse(readFileSync(path, 'utf8')).custom).toBe(42)
    expect(JSON.parse(readFileSync(path, 'utf8')).preview.extra).toBe(true)
    expect(() => saveProjectSettings(authority, { expectedRevision: before.revision, settings })).toThrow('revision conflict')
    expect(() => saveProjectSettings(authority, { expectedRevision: after.revision, settings: { ...settings, preview: { ...settings.preview, url: 'file:///etc/passwd' } } })).toThrow('URL')
    expect(() => saveProjectSettings(authority, { expectedRevision: after.revision, settings: { ...settings, branches: { ...settings.branches, dev: '../bad' } } })).toThrow('branch')
  })
  test('roundtrips native permissions with ordered duplicate rules and quoted keys', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.projectRoot, '.opencode', 'agents'), { recursive: true })
    const path = join(authority.projectRoot, '.opencode', 'agents', 'coder.md')
    const source = `---\n"model":\n  providerID: vendor\n  id: example\n  variant: fast\n\n  # nested comment\n"steps": 3\npermissions:\n  - action: shell\n    resource: "*"\n    effect: deny\n  - action: shell\n    resource: "*"\n    effect: allow\ncustom: keep\n---\nPrompt\n`
    writeFileSync(path, source)
    const before = readAgentDocument(authority, { scope: 'project', agentId: 'coder' })
    expect(before.fields.model).toBe('vendor/example#fast')
    expect(before.fields.permissions.map(rule => rule.effect)).toEqual(['deny', 'allow'])
    const saved = saveAgentDocument(authority, { scope: 'project', agentId: 'coder', expectedRevision: before.revision, fields: { model: 'other/new#v', steps: 4 } })
    const result = readFileSync(path, 'utf8')
    expect(result).toContain('model: "other/new#v"')
    expect(result).not.toContain('"model":')
    expect(result).not.toContain('"steps":')
    expect(result).toContain('permissions:\n  - action: shell')
    expect(saved.fields.permissions).toEqual(before.fields.permissions)
    const reset = saveAgentDocument(authority, { scope: 'project', agentId: 'coder', expectedRevision: saved.revision, fields: { model: '', permissions: before.fields.permissions } })
    expect(reset.fields.model).toBe('')
    expect(reset.fields.permissions).toEqual(before.fields.permissions)
  })
  test('converts legacy permissions only when edited and uses global override before assets', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.configDir, 'agents'))
    writeFileSync(join(authority.configDir, 'agents', 'coder.md'), `---\nmodel: global/model\nvariant: fast\npermission:\n  bash:\n    '*': allow\n    'git push*': deny\n  task: deny\n  supervisor_test: allow\n---\nGlobal prompt\n`)
    const before = readAgentDocument(authority, { scope: 'project', agentId: 'coder' })
    expect(before.fields.system).toBe('Global prompt\n')
    expect(before.fields.model).toBe('global/model#fast')
    expect(before.fields.permissions.map(rule => rule.action)).toEqual(['shell', 'shell', 'subagent', 'supervisor_test'])
    const saved = saveAgentDocument(authority, { scope: 'project', agentId: 'coder', expectedRevision: before.revision, fields: { steps: 5 } })
    const text = readFileSync(saved.target, 'utf8')
    expect(text).toContain('model: "global/model#fast"')
    expect(text).toContain('permissions:')
    expect(text).not.toContain('\npermission:')
    expect(text).not.toContain('\nvariant:')
    expect(saved.fields.permissions).toEqual(before.fields.permissions)
  })
  test('rejects stale inherited defaults', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.configDir, 'agents'))
    const path = join(authority.configDir, 'agents', 'coder.md')
    writeFileSync(path, '---\nmodel: p/m\n---\nFirst')
    const before = readAgentDocument(authority, { scope: 'project', agentId: 'coder' })
    writeFileSync(path, '---\nmodel: p/m\n---\nChanged')
    expect(() => saveAgentDocument(authority, { scope: 'project', agentId: 'coder', expectedRevision: before.revision, fields: { steps: 2 } })).toThrow('revision conflict')
  })
  test('reads project without global directory and returns correct defaults without writes', () => {
    const { authority } = fixture()
    const missing = { ...authority, configDir: join(authority.projectRoot, 'missing') }
    const doc = readAgentDocument(missing, { scope: 'project', agentId: 'coder' })
    expect(doc.fields.model).toBe('')
    expect(readProjectSettings(missing).settings).toBeNull()
    expect(() => readFileSync(join(authority.projectRoot, '.opencode', 'conductor.json'))).toThrow()
    mkdirSync(join(authority.projectRoot, '.opencode'))
    writeFileSync(join(authority.projectRoot, '.opencode', 'conductor.json'), '{}')
    expect(loadProjectSettings(authority.projectRoot)?.branches.dev).toBe('develop')
    expect(loadProjectSettings(authority.projectRoot)?.memory.enabled).toBe(true)
  })
  test('rejects malformed native permission and model shapes', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.projectRoot, '.opencode', 'agents'), { recursive: true })
    const path = join(authority.projectRoot, '.opencode', 'agents', 'coder.md')
    writeFileSync(path, '---\npermissions: [invalid]\n---\nPrompt')
    expect(() => readAgentDocument(authority, { scope: 'project', agentId: 'coder' })).toThrow('Invalid')
    writeFileSync(path, '---\nmodel: { providerID: foo }\n---\nPrompt')
    expect(() => readAgentDocument(authority, { scope: 'project', agentId: 'coder' })).toThrow('model')
  })
  test('retains wildcard and plugin legacy actions when materializing a new override', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.configDir, 'agents'))
    writeFileSync(join(authority.configDir, 'agents', 'coder.md'), `---\npermission:\n  "*": deny\n  "plugin.tool:invoke": ask\n  supervisor_custom: allow\n  bash: deny\n  task: allow\n---\nGlobal prompt\n`)
    const initial = readAgentDocument(authority, { scope: 'project', agentId: 'coder' })
    expect(initial.fields.permissions.map(rule => rule.action)).toEqual(['*', 'plugin.tool:invoke', 'supervisor_custom', 'shell', 'subagent'])
    const saved = saveAgentDocument(authority, { scope: 'project', agentId: 'coder', expectedRevision: initial.revision, fields: { steps: 2 } })
    expect(saved.fields.permissions).toEqual(initial.fields.permissions)
    const malformed = join(authority.configDir, 'agents', 'other.md')
    writeFileSync(malformed, '---\npermission:\n  "plugin.tool": [bad]\n---\nPrompt')
    expect(() => readAgentDocument(authority, { scope: 'project', agentId: 'other' })).toThrow('Invalid permission')
  })
  test('checks for a non-cooperating writer immediately before rename', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.projectRoot, '.opencode', 'agents'), { recursive: true })
    const path = join(authority.projectRoot, '.opencode', 'agents', 'coder.md')
    writeFileSync(path, '---\nmodel: p/m\n---\nOriginal')
    const initial = readAgentDocument(authority, { scope: 'project', agentId: 'coder' })
    __setConfigurationStoreBeforeCommitForTests(() => writeFileSync(path, '---\nmodel: p/m\n---\nExternal edit'))
    expect(() => saveAgentDocument(authority, { scope: 'project', agentId: 'coder', expectedRevision: initial.revision, fields: { steps: 2 } })).toThrow('revision conflict')
    expect(readFileSync(path, 'utf8')).toContain('External edit')
  })
  test('uses effective native template for project creation and detects inherited changes', () => {
    const { authority } = fixture()
    mkdirSync(join(authority.configDir, 'agents'))
    writeFileSync(join(authority.configDir, 'agents', 'coder.md'), '---\nmodel: global/model\n---\nGlobal prompt')
    const effective = { ...authority, inheritedAgent: '---\ndescription: Native description\nmode: subagent\nhidden: true\ncolor: blue\nmodel:\n  providerID: native\n  model: large\n  variant: fast\npermissions:\n  - action: "*"\n    resource: "*"\n    effect: ask\n---\nNative JSONC prompt\n' }
    const initial = readAgentDocument(effective, { scope: 'project', agentId: 'coder' })
    expect(initial.fields.model).toBe('native/large#fast')
    expect(initial.fields.system).toBe('Native JSONC prompt\n')
    expect(() => saveAgentDocument({ ...effective, inheritedAgent: effective.inheritedAgent + 'changed' }, { scope: 'project', agentId: 'coder', expectedRevision: initial.revision, fields: { steps: 2 } })).toThrow('revision conflict')
    const saved = saveAgentDocument(effective, { scope: 'project', agentId: 'coder', expectedRevision: initial.revision, fields: { model: 'new/model' } })
    const raw = readFileSync(saved.target, 'utf8')
    expect(raw).toContain('description: Native description')
    expect(raw).toContain('hidden: true')
    expect(raw).toContain('color: blue')
    expect(saved.fields.system).toBe('Native JSONC prompt\n')
    expect(saved.fields.permissions).toEqual(initial.fields.permissions)
    expect(readAgentDocument(effective, { scope: 'global', agentId: 'coder' }).fields.system).toBe('Global prompt')
  })
})
